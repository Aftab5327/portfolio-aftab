/**
 * Writes data/github-stats.json for /stats: contribution calendar (last ~12
 * months), commits this month, top languages by bytes across non-fork public
 * repos, public repo count and stars. Runs inside the Sync portfolio workflow
 * with its built-in token; that workflow commits data/ when it changes.
 *
 * Usage: npm run github-stats   (needs GITHUB_TOKEN: GitHub's GraphQL API requires auth)
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { formatZodError, githubStatsFileSchema, profileSchema, type GitHubStats } from "../lib/schema";
import { readJson } from "./lib/fs";

const ROOT = process.cwd();
const OUTPUT_PATH = path.join(ROOT, "data", "github-stats.json");
const OUTPUT_COMMENT = "GENERATED by scripts/github-stats.ts during the Sync portfolio workflow. Do not edit by hand.";
const TOP_LANGUAGES = 8;

type GraphQLResponse<T> = { data?: T; errors?: { message: string }[] };

async function graphql<T>(query: string, variables: Record<string, unknown>): Promise<T> {
  const response = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${process.env.GITHUB_TOKEN}`,
      "Content-Type": "application/json",
      "User-Agent": "portfolio-stats"
    },
    body: JSON.stringify({ query, variables })
  });
  if (!response.ok) throw new Error(`GitHub GraphQL ${response.status}: ${(await response.text()).slice(0, 200)}`);
  const body = (await response.json()) as GraphQLResponse<T>;
  if (body.errors?.length) throw new Error(`GitHub GraphQL: ${body.errors.map((error) => error.message).join("; ")}`);
  if (!body.data) throw new Error("GitHub GraphQL returned no data");
  return body.data;
}

const OVERVIEW_QUERY = `
query Overview($login: String!, $from: DateTime!, $to: DateTime!, $monthFrom: DateTime!) {
  user(login: $login) {
    calendar: contributionsCollection(from: $from, to: $to) {
      contributionCalendar { totalContributions weeks { contributionDays { date contributionCount } } }
    }
    month: contributionsCollection(from: $monthFrom, to: $to) { totalCommitContributions }
    allRepos: repositories(privacy: PUBLIC, ownerAffiliations: OWNER) { totalCount }
  }
}`;

const REPOS_QUERY = `
query Repos($login: String!, $after: String) {
  user(login: $login) {
    repositories(first: 100, after: $after, privacy: PUBLIC, ownerAffiliations: OWNER, isFork: false) {
      pageInfo { hasNextPage endCursor }
      nodes {
        stargazerCount
        languages(first: 20, orderBy: { field: SIZE, direction: DESC }) { edges { size node { name color } } }
      }
    }
  }
}`;

type Overview = {
  user: {
    calendar: { contributionCalendar: { totalContributions: number; weeks: { contributionDays: { date: string; contributionCount: number }[] }[] } };
    month: { totalCommitContributions: number };
    allRepos: { totalCount: number };
  } | null;
};

type ReposPage = {
  user: {
    repositories: {
      pageInfo: { hasNextPage: boolean; endCursor: string | null };
      nodes: { stargazerCount: number; languages: { edges: { size: number; node: { name: string; color: string | null } }[] } }[];
    };
  } | null;
};

/** Window ending now, starting on the Sunday 51 weeks before this week's Sunday (≤ 1 year, as GraphQL requires). */
export function calendarWindow(now = new Date()) {
  const thisSunday = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() - now.getUTCDay()));
  const from = new Date(thisSunday.getTime() - 51 * 7 * 86_400_000);
  const monthFrom = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1));
  return { from, to: now, monthFrom, month: monthFrom.toISOString().slice(0, 7) };
}

export async function collectGitHubStats(login: string, now = new Date()): Promise<GitHubStats> {
  const window = calendarWindow(now);
  const overview = await graphql<Overview>(OVERVIEW_QUERY, {
    login,
    from: window.from.toISOString(),
    to: window.to.toISOString(),
    monthFrom: window.monthFrom.toISOString()
  });
  if (!overview.user) throw new Error(`GitHub user "${login}" not found`);

  const languageBytes = new Map<string, { bytes: number; color: string }>();
  let stars = 0;
  let after: string | null = null;
  do {
    const page: ReposPage = await graphql<ReposPage>(REPOS_QUERY, { login, after });
    const repos = page.user?.repositories;
    if (!repos) break;
    for (const repo of repos.nodes) {
      stars += repo.stargazerCount;
      for (const edge of repo.languages.edges) {
        const current = languageBytes.get(edge.node.name) ?? { bytes: 0, color: edge.node.color ?? "#8b949e" };
        current.bytes += edge.size;
        languageBytes.set(edge.node.name, current);
      }
    }
    after = repos.pageInfo.hasNextPage ? repos.pageInfo.endCursor : null;
  } while (after);

  const totalBytes = [...languageBytes.values()].reduce((sum, item) => sum + item.bytes, 0);
  const sorted = [...languageBytes.entries()].sort(([nameA, a], [nameB, b]) => b.bytes - a.bytes || nameA.localeCompare(nameB));
  const top = sorted.slice(0, TOP_LANGUAGES).map(([name, item]) => ({ name, color: item.color, bytes: item.bytes }));
  const otherBytes = sorted.slice(TOP_LANGUAGES).reduce((sum, [, item]) => sum + item.bytes, 0);
  if (otherBytes > 0) top.push({ name: "Other", color: "#8b949e", bytes: otherBytes });

  const calendar = overview.user.calendar.contributionCalendar;
  return {
    username: login,
    calendar: {
      from: window.from.toISOString().slice(0, 10),
      to: window.to.toISOString().slice(0, 10),
      total: calendar.totalContributions,
      weeks: calendar.weeks.map((week) => week.contributionDays.map((day) => ({ date: day.date, count: day.contributionCount })))
    },
    month: window.month,
    commitsThisMonth: overview.user.month.totalCommitContributions,
    publicRepos: overview.user.allRepos.totalCount,
    stars,
    languages: top.map((item) => ({ ...item, percent: totalBytes ? Math.round((item.bytes / totalBytes) * 1000) / 10 : 0 }))
  };
}

export async function main() {
  if (!process.env.GITHUB_TOKEN?.trim()) {
    console.log("\nGitHub stats: GITHUB_TOKEN is not set (GitHub's GraphQL API requires auth); skipped.\n");
    return;
  }

  const profile = profileSchema.parse(await readJson(path.join(ROOT, "content", "profile.json")));
  const stats = await collectGitHubStats(profile.githubUsername);

  const output = { $comment: OUTPUT_COMMENT, stats };
  const validated = githubStatsFileSchema.safeParse(output);
  if (!validated.success) throw new Error(formatZodError(validated.error, "data/github-stats.json"));

  const json = `${JSON.stringify(output, null, 2)}\n`;
  const previous = await readFile(OUTPUT_PATH, "utf8").catch(() => "");
  const changed = json !== previous.replace(/\r\n/g, "\n");
  if (changed) {
    await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
    await writeFile(OUTPUT_PATH, json, "utf8");
  }

  console.log(
    `\nGitHub stats for @${stats.username}: ${stats.calendar.total} contributions (${stats.calendar.from} → ${stats.calendar.to}), ` +
      `${stats.commitsThisMonth} commits in ${stats.month}, ${stats.publicRepos} public repos, ${stats.stars} stars, ` +
      `top languages: ${stats.languages.slice(0, 4).map((language) => `${language.name} ${language.percent}%`).join(", ")}` +
      `\n  data/github-stats.json ${changed ? "written" : "unchanged"}\n`
  );
}

if (require.main === module) {
  main().catch((error: unknown) => {
    console.error(`\nGitHub stats failed: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
