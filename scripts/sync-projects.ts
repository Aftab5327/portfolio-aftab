/**
 * Generates data/projects.json from:
 *   - public GitHub repos tagged with the `portfolio` topic (metadata + PORTFOLIO.md)
 *   - content/case-studies/<slug>.md (approved AI drafts)
 *   - content/manual-projects.json (hand-written entries)
 *
 * Case-study content comes from the first available source:
 *   1. PORTFOLIO.md in the repo   2. content/case-studies/<slug>.md
 *   3. content/manual-projects.json   4. bare repo metadata
 * Fields missing from the chosen source fall back through the lower ones.
 *
 * Usage: npm run sync          (set GITHUB_TOKEN for 5000 req/h instead of 60)
 * See docs/automation.md.
 */
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  formatZodError,
  manualProjectsFileSchema,
  profileSchema,
  projectsFileSchema,
  type CaseStudySource,
  type ManualProject,
  type PortfolioFrontmatter,
  type Project,
  type ProjectSections
} from "../lib/schema";
import {
  PORTFOLIO_FILE,
  PORTFOLIO_TOPIC,
  fetchLanguages,
  fetchRepoFile,
  getRateLimitRemaining,
  humanize,
  isAuthenticated,
  isPortfolioRepo,
  listPublicRepos,
  slugify,
  type GitHubRepo
} from "./lib/github";
import { readJson, readText } from "./lib/fs";
import { emptySections, parsePortfolioMarkdown, type ParsedPortfolio } from "./lib/portfolio-md";

const ROOT = process.cwd();
const PROFILE_PATH = path.join(ROOT, "content", "profile.json");
const MANUAL_PATH = path.join(ROOT, "content", "manual-projects.json");
const CASE_STUDY_DIR = path.join(ROOT, "content", "case-studies");
const OUTPUT_PATH = path.join(ROOT, "data", "projects.json");
const IMAGE_DIR = path.join(ROOT, "public", "projects");

const IMAGE_EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"]);
const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
const OUTPUT_COMMENT =
  "GENERATED by scripts/sync-projects.ts (npm run sync). Do not edit by hand: change the repo's PORTFOLIO.md, content/case-studies/ or content/manual-projects.json instead.";

const warnings: string[] = [];
const warn = (message: string) => warnings.push(message);
const relative = (filePath: string) => path.relative(ROOT, filePath).replace(/\\/g, "/");

// ── Images ───────────────────────────────────────────────────────────────────

/**
 * Resolves an `image` value: https URLs and site paths under /projects/ are kept;
 * anything else is a repo-relative path, downloaded into public/projects/<slug>.<ext>.
 */
async function resolveImage(ref: string | undefined, slug: string, label: string, repo?: GitHubRepo): Promise<string> {
  if (!ref?.trim()) return "";
  const value = ref.trim();
  if (/^https?:\/\//i.test(value) || value.startsWith("/projects/")) return value;

  if (!repo) {
    warn(`${label}: image "${value}" is repo-relative but the project has no synced repo; ignored`);
    return "";
  }

  const clean = path.posix.normalize(value.replace(/^\.?\//, "").replace(/^\//, ""));
  if (clean.startsWith("..")) {
    warn(`${label}: image path "${value}" points outside the repo; ignored`);
    return "";
  }

  const ext = path.posix.extname(clean).toLowerCase();
  if (!IMAGE_EXTENSIONS.has(ext)) {
    warn(`${label}: image "${value}" must be one of ${[...IMAGE_EXTENSIONS].join(", ")}; ignored`);
    return "";
  }

  const response = await fetchRepoFile(repo, clean);
  if (!response) {
    warn(`${label}: image "${value}" not found on ${repo.default_branch}; ignored`);
    return "";
  }

  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length > MAX_IMAGE_BYTES) {
    warn(`${label}: image "${value}" is ${(bytes.length / 1048576).toFixed(1)} MB (max 5 MB); ignored`);
    return "";
  }

  const fileName = `${slug}${ext}`;
  const target = path.join(IMAGE_DIR, fileName);
  await mkdir(IMAGE_DIR, { recursive: true });

  const existing = await readFile(target).catch(() => null);
  if (!existing || !existing.equals(bytes)) await writeFile(target, bytes);

  // Drop an older copy with a different extension (e.g. slug.png → slug.webp).
  for (const other of IMAGE_EXTENSIONS) {
    if (other !== ext) await rm(path.join(IMAGE_DIR, `${slug}${other}`), { force: true });
  }

  return `/projects/${fileName}`;
}

// ── Building entries ─────────────────────────────────────────────────────────

function normalizeHomepage(homepage: string | null): string {
  if (!homepage?.trim()) return "";
  const candidate = /^https?:\/\//i.test(homepage.trim()) ? homepage.trim() : `https://${homepage.trim()}`;
  try {
    return new URL(candidate).toString().replace(/\/$/, "");
  } catch {
    return "";
  }
}

/** Rebuilds a project with a fixed key order so the JSON diffs stay clean. */
function normalize(project: Project): Project {
  return {
    slug: project.slug,
    title: project.title,
    tagline: project.tagline,
    category: project.category,
    stack: project.stack,
    featured: project.featured,
    order: project.order,
    sections: {
      problem: project.sections.problem,
      solution: project.sections.solution,
      result: project.sections.result,
      features: project.sections.features,
      challenges: project.sections.challenges,
      architecture: project.sections.architecture
    },
    repoUrl: project.repoUrl,
    liveUrl: project.liveUrl,
    image: project.image,
    autoScreenshot: project.autoScreenshot,
    caseStudySource: project.caseStudySource,
    stars: project.stars,
    language: project.language,
    languages: project.languages.map((language) => ({ name: language.name, percent: language.percent })),
    topics: project.topics,
    pushedAt: project.pushedAt,
    source: project.source
  };
}

/** Content fields that each source layer can provide. */
type Layer = Partial<Pick<Project, "title" | "tagline" | "category" | "stack" | "featured" | "order" | "liveUrl" | "image" | "autoScreenshot">>;

/** Later layers win; empty strings/arrays and undefined never override. */
function mergeLayers(...layers: Layer[]): Required<Layer> {
  const merged: Required<Layer> = {
    title: "",
    tagline: "",
    category: "",
    stack: [],
    featured: false,
    order: null,
    liveUrl: "",
    image: "",
    autoScreenshot: false
  };
  for (const layer of layers) {
    for (const [key, value] of Object.entries(layer) as [keyof Layer, Layer[keyof Layer]][]) {
      if (value === undefined || value === "" || (Array.isArray(value) && value.length === 0)) continue;
      (merged as Record<string, unknown>)[key] = value;
    }
  }
  return merged;
}

const layerFromRepo = (repo: GitHubRepo, topics: string[]): Layer => ({
  title: humanize(repo.name),
  tagline: repo.description ?? "",
  category: repo.language ?? "Project",
  stack: [...new Set([repo.language, ...topics].filter((item): item is string => Boolean(item)))],
  liveUrl: normalizeHomepage(repo.homepage)
});

const layerFromManual = ({ title, tagline, category, stack, featured, order, liveUrl, image, autoScreenshot }: ManualProject): Layer => ({
  title,
  tagline,
  category,
  stack,
  featured,
  order: order ?? undefined,
  liveUrl,
  image,
  autoScreenshot
});

const layerFromFrontmatter = (frontmatter: PortfolioFrontmatter): Layer => ({ ...frontmatter, image: undefined });

type Sources = {
  slug: string;
  repo?: GitHubRepo;
  portfolioMd?: ParsedPortfolio;
  caseStudy?: ParsedPortfolio;
  manual?: ManualProject;
};

async function buildProject({ slug, repo, portfolioMd, caseStudy, manual }: Sources): Promise<Project> {
  const caseStudySource: CaseStudySource = portfolioMd ? "portfolio-md" : caseStudy ? "case-study" : manual ? "manual" : "metadata";
  const markdown = portfolioMd ?? caseStudy;
  const label = repo?.name ?? slug;

  const topics = (repo?.topics ?? []).filter((topic) => topic !== PORTFOLIO_TOPIC).sort();
  const fields = mergeLayers(
    repo ? layerFromRepo(repo, topics) : {},
    manual ? layerFromManual(manual) : {},
    markdown ? layerFromFrontmatter(markdown.frontmatter) : {}
  );

  const sections: ProjectSections = markdown?.sections ?? manual?.sections ?? emptySections();
  // Markdown images may be repo-relative (downloaded); manual images are site paths or URLs, used as-is.
  const [languages, markdownImage] = await Promise.all([
    repo ? fetchLanguages(repo) : Promise.resolve([]),
    resolveImage(markdown?.frontmatter.image, slug, label, repo)
  ]);
  const image = markdownImage || manual?.image || "";

  return normalize({
    slug,
    title: fields.title || humanize(slug),
    tagline: fields.tagline,
    category: fields.category,
    stack: fields.stack,
    featured: fields.featured,
    order: fields.order,
    sections,
    repoUrl: repo?.html_url ?? manual?.repoUrl ?? "",
    liveUrl: fields.liveUrl,
    image,
    autoScreenshot: fields.autoScreenshot,
    caseStudySource,
    stars: repo?.stargazers_count ?? 0,
    language: repo?.language ?? "",
    languages,
    topics,
    pushedAt: repo?.pushed_at ?? "",
    source: repo ? "github" : "manual"
  });
}

function compareProjects(a: Project, b: Project): number {
  if (a.featured !== b.featured) return a.featured ? -1 : 1;
  const orderA = a.order ?? Number.POSITIVE_INFINITY;
  const orderB = b.order ?? Number.POSITIVE_INFINITY;
  if (orderA !== orderB) return orderA < orderB ? -1 : 1;
  return b.pushedAt.localeCompare(a.pushedAt); // newest first; manual ("") last, in file order
}

// ── Main ─────────────────────────────────────────────────────────────────────

/** Raw content/case-studies/<slug>.md files, keyed by slug (parsed later, once the repo is known). */
async function readCaseStudies(): Promise<Map<string, string>> {
  const files = await readdir(CASE_STUDY_DIR).catch(() => [] as string[]);
  const result = new Map<string, string>();
  for (const file of files.filter((name) => name.endsWith(".md") && name !== "README.md").sort()) {
    const slug = file.slice(0, -3);
    if (slugify(slug) !== slug) {
      warn(`content/case-studies/${file}: file name must be a lowercase slug (e.g. ${slugify(slug)}.md); ignored`);
      continue;
    }
    result.set(slug, await readText(path.join(CASE_STUDY_DIR, file)));
  }
  return result;
}

async function main() {
  const profileResult = profileSchema.safeParse(await readJson(PROFILE_PATH));
  if (!profileResult.success) throw new Error(formatZodError(profileResult.error, relative(PROFILE_PATH)));
  const username = profileResult.data.githubUsername;

  const manualResult = manualProjectsFileSchema.safeParse(await readJson(MANUAL_PATH));
  if (!manualResult.success) throw new Error(formatZodError(manualResult.error, relative(MANUAL_PATH)));
  const manualBySlug = new Map(manualResult.data.projects.map((project) => [project.slug, project]));

  const caseStudyFiles = await readCaseStudies();

  let previous: Project[] = [];
  let previousRaw = "";
  try {
    previousRaw = await readText(OUTPUT_PATH);
    const parsed = projectsFileSchema.safeParse(JSON.parse(previousRaw));
    if (parsed.success) previous = parsed.data.projects;
    else warn(`existing ${relative(OUTPUT_PATH)} doesn't match the current schema and will be regenerated`);
  } catch {
    // First run: no previous output.
  }
  const previousBySlug = new Map(previous.map((project) => [project.slug, project]));

  console.log(`\nPortfolio sync for @${username} (${isAuthenticated() ? "authenticated" : "unauthenticated: 60 req/h"})\n`);

  const repos = await listPublicRepos(username);
  const forks = repos.filter((repo) => repo.fork).length;
  const archived = repos.filter((repo) => !repo.fork && repo.archived).length;
  const tagged = repos.filter(isPortfolioRepo);
  const repoBySlug = new Map(tagged.map((repo) => [slugify(repo.name), repo]));

  // Every slug that has a repo or a manual entry becomes a project.
  const slugs = [...new Set([...repoBySlug.keys(), ...manualBySlug.keys()])];
  for (const slug of caseStudyFiles.keys()) {
    if (!slugs.includes(slug)) warn(`content/case-studies/${slug}.md has no matching tagged repo or manual entry; ignored`);
  }

  const projects: Project[] = [];
  for (const slug of slugs) {
    const repo = repoBySlug.get(slug);
    const manual = manualBySlug.get(slug);
    const caseStudyRaw = caseStudyFiles.get(slug);

    try {
      let portfolioMd: ParsedPortfolio | undefined;
      if (repo) {
        const file = await fetchRepoFile(repo, PORTFOLIO_FILE);
        if (file) portfolioMd = parsePortfolioMarkdown(await file.text(), `${repo.name}/${PORTFOLIO_FILE}`, repo);
      }
      const caseStudy =
        !portfolioMd && caseStudyRaw !== undefined
          ? parsePortfolioMarkdown(caseStudyRaw, `content/case-studies/${slug}.md`, repo)
          : undefined;

      for (const parsed of [portfolioMd, caseStudy]) parsed?.issues.forEach(warn);
      if (repo && !portfolioMd && !caseStudy && !manual) {
        warn(`${repo.name}: no ${PORTFOLIO_FILE}, case study or manual entry; using repo metadata only (run \`npm run draft\`)`);
      }

      projects.push(await buildProject({ slug, repo, portfolioMd, caseStudy, manual }));
    } catch (error) {
      const kept = previousBySlug.get(slug);
      if (kept) {
        projects.push(kept);
        warn(`${slug}: sync failed (${(error as Error).message}); kept previous data`);
      } else {
        warn(`${slug}: sync failed (${(error as Error).message}); skipped`);
      }
    }
  }
  projects.sort(compareProjects);

  const output = { $comment: OUTPUT_COMMENT, projects };
  const validated = projectsFileSchema.safeParse(output);
  if (!validated.success) throw new Error(formatZodError(validated.error, relative(OUTPUT_PATH)));

  // Orphaned images: files in public/projects/ (not auto/) that no project references.
  const referenced = new Set(projects.map((project) => project.image).filter((image) => image.startsWith("/projects/")));
  const imageFiles = await readdir(IMAGE_DIR).catch(() => [] as string[]);
  for (const file of imageFiles) {
    if (IMAGE_EXTENSIONS.has(path.extname(file).toLowerCase()) && !referenced.has(`/projects/${file}`)) {
      warn(`public/projects/${file} is not referenced by any project (delete it if unused)`);
    }
  }

  const json = `${JSON.stringify(output, null, 2)}\n`;
  // Normalise line endings: git on Windows may check the file out with CRLF.
  const changed = json !== previousRaw.replace(/\r\n/g, "\n");
  if (changed) {
    await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
    await writeFile(OUTPUT_PATH, json, "utf8");
  }

  // ── Summary ──
  const nextSlugs = new Set(projects.map((project) => project.slug));
  const added = projects.filter((project) => !previousBySlug.has(project.slug));
  const updated = projects.filter((project) => {
    const before = previousBySlug.get(project.slug);
    return before && JSON.stringify(before) !== JSON.stringify(project);
  });
  const removed = previous.filter((project) => !nextSlugs.has(project.slug));
  const label = (project: Project) => `${project.slug} (${project.caseStudySource})`;
  const list = (items: Project[]) => (items.length ? `\n      ${items.map(label).join("\n      ")}` : "");
  const bySource = (source: CaseStudySource) => projects.filter((project) => project.caseStudySource === source).length;
  const withRepo = projects.filter((project) => project.source === "github").length;

  console.log(`  Repos found:        ${repos.length} public (${forks} fork(s), ${archived} archived skipped)`);
  console.log(`  Tagged "${PORTFOLIO_TOPIC}":   ${tagged.length}${tagged.length ? ` → ${tagged.map((repo) => repo.name).join(", ")}` : ""}`);
  console.log(`  Projects written:   ${projects.length} (${withRepo} with a synced repo, ${projects.length - withRepo} manual-only)`);
  console.log(
    `  Case-study source:  PORTFOLIO.md ${bySource("portfolio-md")}, case-studies/ ${bySource("case-study")}, manual ${bySource("manual")}, metadata ${bySource("metadata")}`
  );
  console.log(`  Added:    ${added.length}${list(added)}`);
  console.log(`  Updated:  ${updated.length}${list(updated)}`);
  console.log(`  Removed:  ${removed.length}${list(removed)}`);
  console.log(`  Output:   ${relative(OUTPUT_PATH)} ${changed ? "written" : "unchanged"}`);
  console.log(`  API rate limit remaining: ${getRateLimitRemaining()}`);
  if (warnings.length) {
    console.log(`\n  Warnings (${warnings.length}):`);
    for (const message of warnings) console.log(`    - ${message}`);
  } else {
    console.log(`\n  Warnings: none`);
  }
  console.log("");
}

main().catch((error: unknown) => {
  console.error(`\nSync failed: ${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
