/**
 * Generates data/projects.json from:
 *   1. public GitHub repos tagged with the `portfolio` topic (PORTFOLIO.md + repo metadata)
 *   2. content/manual-projects.json (hand-written entries; a synced repo with the same slug wins)
 *
 * Usage: npm run sync          (set GITHUB_TOKEN for 5000 req/h instead of 60)
 * See docs/automation.md.
 */
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import matter from "gray-matter";
import {
  FRONTMATTER_KEYS,
  SECTION_KEYS,
  formatZodError,
  manualProjectsFileSchema,
  portfolioFrontmatterSchema,
  profileSchema,
  projectsFileSchema,
  type ManualProject,
  type PortfolioFrontmatter,
  type Project,
  type ProjectSections,
  type SectionKey
} from "../lib/schema";

const ROOT = process.cwd();
const PROFILE_PATH = path.join(ROOT, "content", "profile.json");
const MANUAL_PATH = path.join(ROOT, "content", "manual-projects.json");
const OUTPUT_PATH = path.join(ROOT, "data", "projects.json");
const IMAGE_DIR = path.join(ROOT, "public", "projects");

const PORTFOLIO_TOPIC = "portfolio";
const PORTFOLIO_FILE = "PORTFOLIO.md";
const IMAGE_EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"]);
const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
const OUTPUT_COMMENT =
  "GENERATED by scripts/sync-projects.ts (npm run sync). Do not edit by hand: change content/manual-projects.json or the repo's PORTFOLIO.md instead.";

const SECTION_ALIASES: Record<string, SectionKey> = {
  problem: "problem",
  solution: "solution",
  result: "result",
  results: "result",
  features: "features",
  feature: "features",
  challenges: "challenges",
  challenge: "challenges",
  architecture: "architecture"
};

const warnings: string[] = [];
const warn = (message: string) => warnings.push(message);

// ── GitHub API ───────────────────────────────────────────────────────────────

type GitHubRepo = {
  name: string;
  full_name: string;
  html_url: string;
  description: string | null;
  homepage: string | null;
  language: string | null;
  topics?: string[];
  stargazers_count: number;
  pushed_at: string | null;
  fork: boolean;
  archived: boolean;
  default_branch: string;
};

const token = process.env.GITHUB_TOKEN?.trim();
let rateLimitRemaining = "?";

async function github(pathname: string, accept = "application/vnd.github+json"): Promise<Response> {
  const response = await fetch(`https://api.github.com${pathname}`, {
    headers: {
      Accept: accept,
      "X-GitHub-Api-Version": "2022-11-28",
      "User-Agent": "portfolio-sync",
      ...(token ? { Authorization: `Bearer ${token}` } : {})
    }
  });

  rateLimitRemaining = response.headers.get("x-ratelimit-remaining") ?? rateLimitRemaining;

  if ((response.status === 403 || response.status === 429) && response.headers.get("x-ratelimit-remaining") === "0") {
    const reset = Number(response.headers.get("x-ratelimit-reset")) * 1000;
    const when = Number.isFinite(reset) ? new Date(reset).toISOString() : "later";
    throw new Error(`GitHub API rate limit exceeded (resets ${when}). Set GITHUB_TOKEN to raise the limit.`);
  }

  return response;
}

async function githubJson<T>(pathname: string): Promise<T> {
  const response = await github(pathname);
  if (!response.ok) {
    const body = (await response.text()).slice(0, 200);
    throw new Error(`GET ${pathname} failed: ${response.status} ${body}`);
  }
  return (await response.json()) as T;
}

const encodePath = (filePath: string) => filePath.split("/").map(encodeURIComponent).join("/");

async function listPublicRepos(username: string): Promise<GitHubRepo[]> {
  const repos: GitHubRepo[] = [];
  for (let page = 1; ; page += 1) {
    const batch = await githubJson<GitHubRepo[]>(
      `/users/${encodeURIComponent(username)}/repos?type=owner&sort=pushed&per_page=100&page=${page}`
    );
    repos.push(...batch);
    if (batch.length < 100) return repos;
  }
}

/** Raw file contents from the default branch, or null if the file doesn't exist. */
async function fetchRepoFile(repo: GitHubRepo, filePath: string): Promise<Response | null> {
  const response = await github(
    `/repos/${repo.full_name}/contents/${encodePath(filePath)}?ref=${encodeURIComponent(repo.default_branch)}`,
    "application/vnd.github.raw"
  );
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`fetching ${filePath} failed: ${response.status}`);
  return response;
}

async function fetchLanguages(repo: GitHubRepo): Promise<Project["languages"]> {
  const bytes = await githubJson<Record<string, number>>(`/repos/${repo.full_name}/languages`);
  const total = Object.values(bytes).reduce((sum, value) => sum + value, 0);
  if (total === 0) return [];

  return Object.entries(bytes)
    .sort(([nameA, a], [nameB, b]) => b - a || nameA.localeCompare(nameB))
    .map(([name, value]) => ({ name, percent: Math.round((value / total) * 1000) / 10 }))
    .filter((language) => language.percent >= 0.1);
}

// ── PORTFOLIO.md parsing ─────────────────────────────────────────────────────

const emptySections = (): ProjectSections => ({
  problem: "",
  solution: "",
  result: "",
  features: "",
  challenges: "",
  architecture: ""
});

const isFence = (line: string) => /^\s*(```|~~~)/.test(line);

/** Splits the Markdown body on level-2 headings (ignoring headings inside code fences). */
function splitSections(body: string, repoName: string): ProjectSections {
  const sections = emptySections();
  const lines = body.replace(/\r\n/g, "\n").split("\n");
  let current: SectionKey | null = null;
  let buffer: string[] = [];
  let inFence = false;
  let ignoredText = false;

  const flush = () => {
    if (current) {
      const text = buffer.join("\n").trim();
      sections[current] = sections[current] ? `${sections[current]}\n\n${text}` : text;
    }
    buffer = [];
  };

  for (const line of lines) {
    if (isFence(line)) inFence = !inFence;

    const heading = inFence ? null : line.match(/^##\s+(.+?)\s*#*\s*$/);
    if (heading) {
      flush();
      const key = SECTION_ALIASES[heading[1].toLowerCase().replace(/[^a-z]/g, "")];
      if (!key) warn(`${repoName}: unknown section "## ${heading[1]}" ignored (expected ${SECTION_KEYS.join(", ")})`);
      current = key ?? null;
      continue;
    }

    if (current) buffer.push(line);
    else if (line.trim() && !/^#\s/.test(line)) ignoredText = true;
  }
  flush();

  if (ignoredText) warn(`${repoName}: text outside a ## section was ignored`);
  return sections;
}

/** Makes relative links/images inside synced Markdown point at GitHub (outside code fences). */
function absolutizeMarkdown(markdown: string, repo: GitHubRepo): string {
  if (!markdown) return markdown;

  const resolve = (target: string, kind: "raw" | "blob") => {
    if (/^([a-z][a-z0-9+.-]*:|#|\/\/)/i.test(target)) return target;
    const clean = path.posix.normalize(target.replace(/^\.?\//, "").replace(/^\//, ""));
    if (clean.startsWith("..")) return target;
    return kind === "raw"
      ? `https://raw.githubusercontent.com/${repo.full_name}/${repo.default_branch}/${encodePath(clean)}`
      : `${repo.html_url}/blob/${repo.default_branch}/${encodePath(clean)}`;
  };

  let inFence = false;
  return markdown
    .split("\n")
    .map((line) => {
      if (isFence(line)) {
        inFence = !inFence;
        return line;
      }
      if (inFence) return line;
      return line
        .replace(/(!\[[^\]]*\]\()\s*([^)\s]+)/g, (_m, prefix: string, target: string) => prefix + resolve(target, "raw"))
        .replace(/((?:^|[^!])\[[^\]]*\]\()\s*([^)\s]+)/g, (_m, prefix: string, target: string) => prefix + resolve(target, "blob"));
    })
    .join("\n");
}

function parsePortfolioFile(markdown: string, repo: GitHubRepo): { frontmatter: PortfolioFrontmatter; sections: ProjectSections } {
  let parsed: matter.GrayMatterFile<string>;
  try {
    parsed = matter(markdown);
  } catch (error) {
    warn(`${repo.name}: could not parse ${PORTFOLIO_FILE} frontmatter (${(error as Error).message}); using repo metadata only`);
    return { frontmatter: {}, sections: emptySections() };
  }

  const unknownKeys = Object.keys(parsed.data).filter((key) => !FRONTMATTER_KEYS.includes(key));
  if (unknownKeys.length) warn(`${repo.name}: unknown frontmatter key(s) ignored: ${unknownKeys.join(", ")}`);

  // Drop only the invalid fields so one typo doesn't discard the whole frontmatter.
  const data: Record<string, unknown> = { ...parsed.data };
  let result = portfolioFrontmatterSchema.safeParse(data);
  if (!result.success) {
    for (const issue of result.error.issues) {
      const field = String(issue.path[0] ?? "");
      warn(`${repo.name}: frontmatter "${field}" is invalid (${issue.message}); ignored`);
      delete data[field];
    }
    result = portfolioFrontmatterSchema.safeParse(data);
  }
  const frontmatter: PortfolioFrontmatter = result.success ? result.data : {};

  const sections = splitSections(parsed.content, repo.name);
  for (const key of SECTION_KEYS) sections[key] = absolutizeMarkdown(sections[key], repo);

  return { frontmatter, sections };
}

// ── Images ───────────────────────────────────────────────────────────────────

const managedImages = new Set<string>();

async function resolveImage(ref: string | undefined, repo: GitHubRepo, slug: string): Promise<string> {
  if (!ref?.trim()) return "";
  const value = ref.trim();
  if (/^https?:\/\//i.test(value)) return value;

  const clean = path.posix.normalize(value.replace(/^\.?\//, "").replace(/^\//, ""));
  if (clean.startsWith("..")) {
    warn(`${repo.name}: image path "${value}" points outside the repo; ignored`);
    return "";
  }

  const ext = path.posix.extname(clean).toLowerCase();
  if (!IMAGE_EXTENSIONS.has(ext)) {
    warn(`${repo.name}: image "${value}" must be one of ${[...IMAGE_EXTENSIONS].join(", ")}; ignored`);
    return "";
  }

  const response = await fetchRepoFile(repo, clean);
  if (!response) {
    warn(`${repo.name}: image "${value}" not found on ${repo.default_branch}; ignored`);
    return "";
  }

  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length > MAX_IMAGE_BYTES) {
    warn(`${repo.name}: image "${value}" is ${(bytes.length / 1048576).toFixed(1)} MB (max 5 MB); ignored`);
    return "";
  }

  const fileName = `${slug}${ext}`;
  const target = path.join(IMAGE_DIR, fileName);
  await mkdir(IMAGE_DIR, { recursive: true });

  const existing = await readFile(target).catch(() => null);
  if (!existing || !existing.equals(bytes)) await writeFile(target, bytes);
  managedImages.add(fileName);

  // Drop an older copy with a different extension (e.g. slug.png → slug.webp).
  for (const other of IMAGE_EXTENSIONS) {
    if (other !== ext) await rm(path.join(IMAGE_DIR, `${slug}${other}`), { force: true });
  }

  return `/projects/${fileName}`;
}

// ── Building entries ─────────────────────────────────────────────────────────

const slugify = (name: string) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const humanize = (name: string) =>
  name
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ");

function normalizeHomepage(homepage: string | null): string {
  if (!homepage?.trim()) return "";
  const candidate = /^https?:\/\//i.test(homepage.trim()) ? homepage.trim() : `https://${homepage.trim()}`;
  try {
    return new URL(candidate).toString().replace(/\/$/, "");
  } catch {
    return "";
  }
}

/** Rebuilds a project with a fixed key order so the JSON diffs stay clean. */
function normalize(project: Project): Project {
  return {
    slug: project.slug,
    title: project.title,
    tagline: project.tagline,
    category: project.category,
    stack: project.stack,
    featured: project.featured,
    order: project.order,
    sections: {
      problem: project.sections.problem,
      solution: project.sections.solution,
      result: project.sections.result,
      features: project.sections.features,
      challenges: project.sections.challenges,
      architecture: project.sections.architecture
    },
    repoUrl: project.repoUrl,
    liveUrl: project.liveUrl,
    image: project.image,
    stars: project.stars,
    language: project.language,
    languages: project.languages.map((language) => ({ name: language.name, percent: language.percent })),
    topics: project.topics,
    pushedAt: project.pushedAt,
    source: project.source
  };
}

const fromManual = (project: ManualProject): Project =>
  normalize({ ...project, stars: 0, language: "", languages: [], topics: [], pushedAt: "", source: "manual" });

async function buildFromRepo(repo: GitHubRepo): Promise<Project> {
  const slug = slugify(repo.name);
  const file = await fetchRepoFile(repo, PORTFOLIO_FILE);

  let frontmatter: PortfolioFrontmatter = {};
  let sections = emptySections();
  if (file) {
    ({ frontmatter, sections } = parsePortfolioFile(await file.text(), repo));
  } else {
    warn(`${repo.name}: no ${PORTFOLIO_FILE} on ${repo.default_branch}; using a minimal entry from repo metadata`);
  }

  const topics = (repo.topics ?? []).filter((topic) => topic !== PORTFOLIO_TOPIC).sort();
  const [languages, image] = await Promise.all([fetchLanguages(repo), resolveImage(frontmatter.image, repo, slug)]);

  return normalize({
    slug,
    title: frontmatter.title ?? humanize(repo.name),
    tagline: frontmatter.tagline ?? repo.description ?? "",
    category: frontmatter.category ?? repo.language ?? "Project",
    stack: frontmatter.stack ?? [...new Set([repo.language, ...topics].filter((item): item is string => Boolean(item)))],
    featured: frontmatter.featured ?? false,
    order: frontmatter.order ?? null,
    sections,
    repoUrl: repo.html_url,
    liveUrl: frontmatter.liveUrl || normalizeHomepage(repo.homepage),
    image,
    stars: repo.stargazers_count,
    language: repo.language ?? "",
    languages,
    topics,
    pushedAt: repo.pushed_at ?? "",
    source: "github"
  });
}

function compareProjects(a: Project, b: Project): number {
  if (a.featured !== b.featured) return a.featured ? -1 : 1;
  const orderA = a.order ?? Number.POSITIVE_INFINITY;
  const orderB = b.order ?? Number.POSITIVE_INFINITY;
  if (orderA !== orderB) return orderA < orderB ? -1 : 1;
  return b.pushedAt.localeCompare(a.pushedAt); // newest first; manual ("") last, in file order
}

// ── Main ─────────────────────────────────────────────────────────────────────

async function readJson(filePath: string): Promise<unknown> {
  return JSON.parse(await readFile(filePath, "utf8"));
}

async function main() {
  const relative = (filePath: string) => path.relative(ROOT, filePath).replace(/\\/g, "/");

  const profileResult = profileSchema.safeParse(await readJson(PROFILE_PATH));
  if (!profileResult.success) throw new Error(formatZodError(profileResult.error, relative(PROFILE_PATH)));
  const username = profileResult.data.githubUsername;

  const manualResult = manualProjectsFileSchema.safeParse(await readJson(MANUAL_PATH));
  if (!manualResult.success) throw new Error(formatZodError(manualResult.error, relative(MANUAL_PATH)));
  const manual = manualResult.data.projects.map(fromManual);

  let previous: Project[] = [];
  let previousRaw = "";
  try {
    previousRaw = await readFile(OUTPUT_PATH, "utf8");
    const parsed = projectsFileSchema.safeParse(JSON.parse(previousRaw));
    if (parsed.success) previous = parsed.data.projects;
    else warn(`existing ${relative(OUTPUT_PATH)} is invalid and will be regenerated`);
  } catch {
    // First run: no previous output.
  }
  const previousBySlug = new Map(previous.map((project) => [project.slug, project]));

  console.log(`\nPortfolio sync for @${username} (${token ? "authenticated" : "unauthenticated: 60 req/h"})\n`);

  const repos = await listPublicRepos(username);
  const forks = repos.filter((repo) => repo.fork).length;
  const archived = repos.filter((repo) => !repo.fork && repo.archived).length;
  const candidates = repos.filter((repo) => !repo.fork && !repo.archived);
  const tagged = candidates.filter((repo) => repo.topics?.includes(PORTFOLIO_TOPIC));

  const synced: Project[] = [];
  for (const repo of tagged) {
    try {
      synced.push(await buildFromRepo(repo));
    } catch (error) {
      const kept = previousBySlug.get(slugify(repo.name));
      if (kept?.source === "github") {
        synced.push(kept);
        warn(`${repo.name}: sync failed (${(error as Error).message}); kept previous data`);
      } else {
        warn(`${repo.name}: sync failed (${(error as Error).message}); skipped`);
      }
    }
  }

  const merged = new Map(manual.map((project) => [project.slug, project]));
  const overridden: string[] = [];
  for (const project of synced) {
    if (merged.get(project.slug)?.source === "manual") overridden.push(project.slug);
    merged.set(project.slug, project);
  }
  const projects = [...merged.values()].sort(compareProjects);

  const output = { $comment: OUTPUT_COMMENT, projects };
  const validated = projectsFileSchema.safeParse(output);
  if (!validated.success) throw new Error(formatZodError(validated.error, relative(OUTPUT_PATH)));

  // Orphaned images: files in public/projects/ that no project references.
  const referenced = new Set(projects.map((project) => project.image).filter((image) => image.startsWith("/projects/")));
  const imageFiles = await readdir(IMAGE_DIR).catch(() => [] as string[]);
  for (const file of imageFiles) {
    if (IMAGE_EXTENSIONS.has(path.extname(file).toLowerCase()) && !referenced.has(`/projects/${file}`)) {
      warn(`public/projects/${file} is not referenced by any project (delete it if unused)`);
    }
  }

  const json = `${JSON.stringify(output, null, 2)}\n`;
  // Normalise line endings: git on Windows may check the file out with CRLF.
  const changed = json !== previousRaw.replace(/\r\n/g, "\n");
  if (changed) {
    await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
    await writeFile(OUTPUT_PATH, json, "utf8");
  }

  // ── Summary ──
  const nextSlugs = new Set(projects.map((project) => project.slug));
  const added = projects.filter((project) => !previousBySlug.has(project.slug));
  const updated = projects.filter((project) => {
    const before = previousBySlug.get(project.slug);
    return before && JSON.stringify(before) !== JSON.stringify(project);
  });
  const removed = previous.filter((project) => !nextSlugs.has(project.slug));
  const label = (project: Project) => `${project.slug} (${project.source})`;
  const list = (items: Project[]) => (items.length ? `\n      ${items.map(label).join("\n      ")}` : "");

  console.log(`  Repos found:        ${repos.length} public (${forks} fork(s), ${archived} archived skipped)`);
  console.log(`  Tagged "${PORTFOLIO_TOPIC}":   ${tagged.length}${tagged.length ? ` → ${tagged.map((repo) => repo.name).join(", ")}` : ""}`);
  console.log(`  Manual entries:     ${manual.length} (${overridden.length} overridden by synced repos${overridden.length ? `: ${overridden.join(", ")}` : ""})`);
  console.log(`  Projects written:   ${projects.length} (${synced.length} github, ${projects.length - synced.length} manual)`);
  console.log(`  Added:    ${added.length}${list(added)}`);
  console.log(`  Updated:  ${updated.length}${list(updated)}`);
  console.log(`  Removed:  ${removed.length}${list(removed)}`);
  console.log(`  Output:   ${relative(OUTPUT_PATH)} ${changed ? "written" : "unchanged"}`);
  console.log(`  API rate limit remaining: ${rateLimitRemaining}`);
  if (warnings.length) {
    console.log(`\n  Warnings (${warnings.length}):`);
    for (const message of warnings) console.log(`    - ${message}`);
  } else {
    console.log(`\n  Warnings: none`);
  }
  console.log("");
}

main().catch((error: unknown) => {
  console.error(`\nSync failed: ${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
